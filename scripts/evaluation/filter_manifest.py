#!/usr/bin/env python3
"""Filter an Evaluation V1 manifest to a runnable tier subset.

By default `sealed_final` is excluded. Pass `--allow-sealed` only for a
registered milestone run.
"""

from __future__ import annotations

import argparse
import json
import tempfile
from collections import Counter
from pathlib import Path


def load_rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def atomic_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
        tmp = Path(handle.name)
    tmp.replace(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--tiers", default="diagnostic_visible,regression_selection", help="Comma-separated tiers")
    parser.add_argument("--allow-sealed", action="store_true")
    args = parser.parse_args()

    allowed = {t.strip() for t in args.tiers.split(",") if t.strip()}
    if "sealed_final" in allowed and not args.allow_sealed:
        raise SystemExit("sealed_final requires --allow-sealed; refusing to filter sealed rows")
    rows = load_rows(args.manifest)
    selected = [r for r in rows if r.get("tier") in allowed]
    counts = Counter(r.get("tier") for r in selected)
    atomic_jsonl(args.out, selected)
    report = {
        "manifest": str(args.manifest),
        "out": str(args.out),
        "tiers": sorted(allowed),
        "input_rows": len(rows),
        "selected_rows": len(selected),
        "tier_counts": dict(sorted(counts.items())),
    }
    cleanup = args.out.parent / "cleanup_report.md"
    if cleanup.exists() and f"`{args.out.name}`" not in cleanup.read_text(encoding="utf-8"):
        with cleanup.open("a", encoding="utf-8") as handle:
            handle.write(f"- `{args.out.name}` ({args.out.stat().st_size} bytes) — generated by filter_manifest.py\n")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
