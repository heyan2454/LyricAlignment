#!/usr/bin/env python3
"""Build a dataset compatibility matrix for productizing Lyric Align on new data."""

from __future__ import annotations

import argparse
import json
import tempfile
from collections import Counter, defaultdict
from pathlib import Path


def load_rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def atomic_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as handle:
        json.dump(value, handle, ensure_ascii=False, sort_keys=True, indent=2)
        handle.write("\n")
        tmp = Path(handle.name)
    tmp.replace(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    rows = load_rows(args.manifest)
    datasets = sorted({r["dataset_id"] for r in rows})
    matrix = []
    for ds in datasets:
        sub = [r for r in rows if r["dataset_id"] == ds]
        tier_counts = Counter(r["tier"] for r in sub)
        groups = len({r["group_id"] for r in sub})
        audio_rows = sum(1 for r in sub if r.get("audio_relpath"))
        langs = sorted({r.get("language", "") for r in sub})
        granularities = sorted({r.get("annotation_granularity", "") for r in sub})
        entry = {
            "dataset_id": ds,
            "groups": groups,
            "rows": len(sub),
            "audio_rows": audio_rows,
            "languages": langs,
            "annotation_granularities": granularities,
            "tier_counts": dict(sorted(tier_counts.items())),
        }
        # Static productization notes.
        if ds == "mir_mlpop_cmn":
            entry.update({
                "vocal_ready": False,
                "input_status": "raw_mixture_partial_audio",
                "required_before_use": ["vocal derivation", "license review"],
                "suggested_role": "natural pop alignment regression",
            })
        elif ds == "mir_mlpop_yue":
            entry.update({
                "vocal_ready": False,
                "input_status": "raw_mixture_partial_audio",
                "required_before_use": ["vocal derivation", "license review"],
                "suggested_role": "Cantonese exploratory probe",
            })
        elif ds == "jamendolyrics_en":
            entry.update({
                "vocal_ready": False,
                "input_status": "raw_mixture_complete",
                "required_before_use": ["vocal derivation", "per-track license retention"],
                "suggested_role": "English word-level alignment regression",
            })
        elif ds == "pjs":
            entry.update({
                "vocal_ready": True,
                "input_status": "complete",
                "required_before_use": ["Japanese phoneme/label mapping"],
                "suggested_role": "Japanese phoneme boundary calibration",
            })
        elif ds == "gtsinger_chinese":
            entry.update({
                "vocal_ready": True,
                "input_status": "complete_selected",
                "required_before_use": ["upstream terms clarification"],
                "suggested_role": "Chinese phoneme/technique stress tests",
            })
        else:
            entry.update({
                "vocal_ready": None,
                "input_status": "unknown",
                "required_before_use": [],
                "suggested_role": "",
            })
        matrix.append(entry)

    payload = {
        "schema_version": "dataset_compatibility_matrix_v1",
        "datasets": matrix,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    atomic_json(args.out, payload)
    cleanup = args.out.parent / "cleanup_report.md"
    if cleanup.exists() and f"`{args.out.name}`" not in cleanup.read_text(encoding="utf-8"):
        with cleanup.open("a", encoding="utf-8") as handle:
            handle.write(f"- `{args.out.name}` ({args.out.stat().st_size} bytes) — generated by build_dataset_compatibility.py\n")
    print(json.dumps({"out": str(args.out), "dataset_count": len(matrix)}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
