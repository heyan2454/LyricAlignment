#!/usr/bin/env python3
"""Build a GTSinger diagnostic run manifest from the Evaluation V1 split.

Each row points to the GTSinger WAV, JSON GT, and a lyrics.txt path (to be
generated by build_gtsinger_lyrics.py).
"""

from __future__ import annotations

import argparse
import json
import tempfile
from pathlib import Path

DEFAULT_DATASETS_ROOT = Path("/home/hyan/Data/datasets")


def load_rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def atomic_jsonl(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, delete=False) as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
        tmp = Path(handle.name)
    tmp.replace(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, required=True, help="diagnostic-only split manifest jsonl")
    parser.add_argument("--datasets-root", type=Path, default=DEFAULT_DATASETS_ROOT)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    rows = load_rows(args.manifest)
    selected = []
    for row in rows:
        if row.get("dataset_id") != "gtsinger_chinese":
            continue
        audio_rel = row.get("audio_relpath")
        if not audio_rel:
            continue
        gts_root = args.datasets_root / "gtsinger_chinese"
        audio_abs = gts_root / audio_rel
        gt_abs = audio_abs.with_suffix(".json")
        if not audio_abs.is_file() or not gt_abs.is_file():
            continue
        selected.append({
            "item_id": row.get("item_id"),
            "group_id": row.get("group_id"),
            "tier": row.get("tier"),
            "audio_abs": str(audio_abs),
            "gt_json_abs": str(gt_abs),
            "lyrics_txt_rel": f"lyrics/{row.get('item_id')}.txt",
            "language": "zh",
        })
    atomic_jsonl(args.out, selected)
    print(json.dumps({"out": str(args.out), "gtsinger_diagnostic_items": len(selected)}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
