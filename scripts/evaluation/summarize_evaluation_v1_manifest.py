#!/usr/bin/env python3
"""Render a human-readable summary from an Evaluation V1 split manifest."""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path


def load_rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def fmt_sec(value: float | None) -> str:
    if value is None:
        return "-"
    return f"{value:.1f}s"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    rows = load_rows(args.manifest)
    datasets = sorted({r["dataset_id"] for r in rows})
    lines = [
        "# Evaluation V1 Manifest Summary",
        "",
        f"- Manifest: `{args.manifest}`",
        f"- Rows: {len(rows)}",
        "",
    ]
    for ds in datasets:
        ds_rows = [r for r in rows if r["dataset_id"] == ds]
        groups = sorted({r["group_id"] for r in ds_rows})
        tiers = Counter(r["tier"] for r in ds_rows)
        audio_rows = [r for r in ds_rows if r.get("audio_relpath")]
        duration = sum(float(r.get("duration_sec") or 0.0) for r in ds_rows)
        lines += [
            f"## {ds}",
            "",
            f"- Groups: {len(groups)}",
            f"- Rows: {len(ds_rows)} (audio rows: {len(audio_rows)})",
            f"- Duration (sum of annotated audio): {fmt_sec(duration)}",
            f"- Tier row counts: {dict(sorted(tiers.items()))}",
            "",
        ]
        if ds == "jamendolyrics_en":
            lines += ["### Hard-case tags by tier", "", "| Tier | Songs | overlap | polyphonic | non_lexical |", "|---|---:|---:|---:|---:|"]
            for tier in ("diagnostic_visible", "regression_selection", "sealed_final"):
                sub = [r for r in ds_rows if r["tier"] == tier]
                songs = len({r["group_id"] for r in sub})
                overlap = sum(1 for r in sub if r.get("metadata", {}).get("lyric_overlap"))
                poly = sum(1 for r in sub if r.get("metadata", {}).get("polyphonic"))
                nonlex = sum(1 for r in sub if r.get("metadata", {}).get("non_lexical"))
                lines.append(f"| {tier} | {songs} | {overlap} | {poly} | {nonlex} |")
            lines.append("")
        if ds == "mir_mlpop_cmn":
            lines += ["### Official split by tier", "", "| Tier | Train | Test |", "|---|---:|---:|"]
            for tier in ("diagnostic_visible", "regression_selection", "sealed_final"):
                sub = [r for r in ds_rows if r["tier"] == tier]
                train = sum(1 for r in sub if r.get("source_split") == "Train")
                test = sum(1 for r in sub if r.get("source_split") == "Test")
                lines.append(f"| {tier} | {train} | {test} |")
            lines.append("")
        if ds == "gtsinger_chinese":
            lines += ["### Song roots by tier", ""]
            by_tier: dict[str, set[str]] = defaultdict(set)
            for r in ds_rows:
                by_tier[r["tier"]].add(r["song_id"])
            for tier in ("diagnostic_visible", "regression_selection", "sealed_final"):
                lines.append(f"- {tier}: {len(by_tier[tier])} roots — {', '.join(sorted(by_tier[tier]))}")
            lines.append("")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    cleanup = args.out.parent / "cleanup_report.md"
    if cleanup.exists() and f"`{args.out.name}`" not in cleanup.read_text(encoding="utf-8"):
        with cleanup.open("a", encoding="utf-8") as handle:
            handle.write(f"- `{args.out.name}` ({args.out.stat().st_size} bytes) — generated by summarize_evaluation_v1_manifest.py\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
